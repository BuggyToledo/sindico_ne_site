function enrichCase(item: ServiceCaseStudy): ServiceCaseStudy {
  const paragraphsHtml = item.paragraphs
    .map((p) => `<p>${p}</p>`)
    .join("\n");
  const resultsHtml =
    item.results && item.results.length > 0
      ? `<h2>Resultados Alcançados no Condomínio (${item.neighborhood})</h2>\n<ul>\n${item.results
          .map((r) => `  <li>${r}</li>`)
          .join("\n")}\n</ul>\n<blockquote><p>${item.ctaQuestion}</p></blockquote>`
      : "";
  return {
    ...item,
    seoTitle: item.seo.title,
    seoDescription: item.seo.description,
    contentHtml: `${paragraphsHtml}\n${resultsHtml}`,
  };
}

export function getServiceCaseBySlug(slug: string): ServiceCaseStudy | undefined {
  const found = SERVICE_CASES.find((c) => c.slug === slug);
  return found ? enrichCase(found) : undefined;
}

export function getServiceCasesByTypeSlug(slug: string): ServiceCaseStudy[] {
  return SERVICE_CASES.filter((c) => c.serviceTypeSlug === slug).map(enrichCase);
}

export function getServiceTypeBySlug(
  slug: string
): ServiceTypeTaxonomy | undefined {
  return SERVICE_TYPES.find((t) => t.slug === slug);
}
